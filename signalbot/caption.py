def _rng(*parts: object) -> random.Random:
    h = hashlib.sha256("|".join(map(str, parts)).encode()).hexdigest()
    return random.Random(int(h[:12], 16))


def levels_block(idea: Idea) -> str:
    """Строки ТВХ / ТП / СЛ — числа считает бот."""
    lines = []
    if idea.entry_conservative:
        extra = f" (по рынку {fmt_num(idea.entry_aggressive)})" if idea.entry_aggressive else ""
        lines.append(f"<b>ТВХ:</b> {fmt_num(idea.entry_conservative)}{extra}")
    for k, p in enumerate(idea.pools, 1):
        lines.append(f"<b>ТП{k}:</b> {fmt_num(p.price)}")
    if idea.invalidation:
        lines.append(f"<b>СЛ:</b> {fmt_num(idea.invalidation)}")
    return "\n".join(lines)


def _template_text(idea: Idea, day: str) -> tuple[str, str]:
    r = _rng(idea.ticker, day, idea.side.value)
    parts = [r.choice(_INTRO[idea.side]).format(t=escape(idea.ticker)), r.choice(_CONFIRM[idea.side])]
    if r.random() < 0.4:
        parts.append(r.choice(_JOKES))
    parts.append(r.choice(_TARGETS[idea.side]))
    return " ".join(parts), r.choice(_AGGR)


def build_caption(idea: Idea, day: str, disclaimer: bool = False, text: PostText | None = None) -> str:
    """Пост: заголовок, мнение, цитата про риск, блок ТВХ/ТП/СЛ. `text` — от Claude, иначе шаблоны."""
    head = f"<b>{escape(idea.ticker)}</b> {'🔥' if idea.side is Side.LONG else '📉'}"
    tail = [levels_block(idea)] + ([f"<i>{DISCLAIMER}</i>"] if disclaimer else [])

    def assemble(opinion: str, risk: str) -> str:
        return "\n\n".join(x for x in [head, escape(opinion), f"<blockquote>{escape(risk)}</blockquote>", *tail] if x)

    if text is not None:
        out = assemble(text.opinion, text.risk_line)
        if len(out) <= MAX_CAPTION:
            return out
    opinion, risk = _template_text(idea, day)
    return assemble(opinion, risk)


def plain_summary(caption_html: str) -> str:
    """Для базы: текст без тегов, чтобы показывать модели прошлые посты (анти-повтор)."""
    import re

    return re.sub(r"<[^>]+>", "", caption_html).replace("&lt;", "<").replace("&gt;", ">").replace("&amp;", "&")


# --- апдейты (ответом на исходный пост) -----------------------------------------------------
def _pct(t: Tracked, price: float) -> float:
    d = 1 if t.side is Side.LONG else -1
    return (price - t.entry_price) / t.entry_price * 100 * d


def update_text(t: Tracked, ev: Event) -> str:
    tk = escape(t.symbol.split("/")[0])
    r = _rng(t.symbol, ev.kind, ev.n, ev.ts)
    if ev.kind == "BREAKOUT":
        way = "выше" if t.side is Side.LONG else "ниже"
        tail = r.choice(["Сделка с подтверждением активна.", "Теперь можно заходить с подтверждением.", "Дальше по плану."])
        return f"<b>{tk}</b>: пробой произошёл ✅\nДневная свеча закрылась {way} уровня ({fmt_num(ev.price)}). {tail}"
    if ev.kind == "TP":
        tail = r.choice(["Едем дальше.", "Красиво.", "Так и работаем.", "Идём по плану."])
        return f"<b>{tk}</b>: цель {ev.n} из {len(t.pools)} взята 🎯\nУровень {fmt_num(ev.price)} · {_pct(t, ev.price):+.1f}% от входа. {tail}"
    if ev.kind == "DONE":
        tail = r.choice(["Все цели закрыты.", "Идея отработала полностью.", "Забираем и идём дальше."])
        return f"<b>{tk}</b>: все цели отработаны 🏆\n{tail} Результат по идее: {t.result_pct:+.1f}% ({t.r_multiple:+.2f}R)."
    if ev.kind == "STOP":
        tail = r.choice(["Бывает, стоп — часть работы.", "Рынок решил иначе, идём дальше.", "Убыток небольшой, нервы целы."])
        return f"<b>{tk}</b>: стоп ❌\nИдея не сработала, закрыта по {fmt_num(ev.price)}. {tail} Результат: {t.result_pct:+.1f}% ({t.r_multiple:+.2f}R)."
    if ev.kind == "CANCEL":
        tail = r.choice(["Сценарий сломан ещё до пробоя.", "Не дождались пробоя, структура поплыла."])
        return f"<b>{tk}</b>: идея отменена ❌\n{tail} Уровень {fmt_num(ev.price)} потерян."
    if ev.kind == "EXPIRED":
        tail = r.choice(["Пробоя не было слишком долго, сценарий снимаю.", "Рынок не торопится, а ждать вечно смысла нет."])
        return f"<b>{tk}</b>: идея неактуальна ❌\n{tail}"
    raise ValueError(ev.kind)
